/* sapi_table.c — fill the sAPI dispatch table by RESOLVER-REPLAY (../standalone_sapi_test.md RESULT 10).
 *
 * The earlier bake path (memcpy a captured table) only covered 0x7e1e2000+ and MISSED the 58 slots below
 * 0x7e1e2000 (e.g. the GNSS URC-attach 0x7e1e1f88) -> GNSS NMEA delivery failed. Instead we replay init1's
 * resolve loop: for each (hash,slot) pair, *slot = resolver(hash), where `resolver` is the r0 the loader
 * passes at boot (start.S stashed it at 0x7e1e2444; RESULT 5). This fills the COMPLETE table, low slots
 * included. The 2 slots init1 doesn't fill (populated by other init fns in the vendor) are added as
 * constant supplements so coverage matches. Pairs are generated by gen_pairs.py from the vendor image.
 */
#include "sapi.h"
#include "sapi_pairs.h"

typedef u32 (*resolver_fn)(u32 hash, u32 zero);   /* init1 calls resolver(r0=hash, r1=0) -> ptr */

int sapi_table_fill(u32 loader_resolver)
{
    resolver_fn rv = (resolver_fn)loader_resolver;
    if (!rv)
        rv = *(resolver_fn *)RESOLVER_SLOT;       /* fallback to the boot-stashed resolver */

    for (unsigned i = 0; i < SAPI_N_PAIRS; i++)
        *(volatile u32 *)sapi_pairs[i].slot = rv(sapi_pairs[i].hash, 0);

    for (unsigned i = 0; i < SAPI_N_SUPP; i++)
        *(volatile u32 *)sapi_supp[i].slot = sapi_supp[i].val;

    return *(volatile u32 *)SLOT_VCOM_WRITE != 0; /* sanity: a known slot got populated */
}
