#!/usr/bin/env python3
"""gen_table.py — emit sapi_table_baked.h from a captured sAPI table dump.

The bake path (../standalone_sapi_test.md RESULT 2/5): a standalone carries the constant fn pointers and
memcpy's them into 0x7E1E2000. The 3 per-boot dynamic tail slots (idx 529/530/532) are NOT baked (left 0).

  python3 gen_table.py ../fromsrc/sapi_table_boot1.bin sapi_table_baked.h
"""
import sys, struct

DYNAMIC = {529, 530, 532}   # per-boot values — never bake these


def main():
    src, out = sys.argv[1], sys.argv[2]
    d = open(src, "rb").read()
    n = len(d) // 4
    w = list(struct.unpack("<%dI" % n, d))
    for i in DYNAMIC:
        if i < n:
            w[i] = 0
    nz = sum(1 for x in w if x)
    lines = [
        "/* sapi_table_baked.h — GENERATED by gen_table.py from a captured table. Do not edit. */",
        "/* %d words, %d non-zero constant pointers; dynamic slots %s zeroed. */"
        % (n, nz, sorted(DYNAMIC)),
        "#ifndef SAPI_TABLE_BAKED_H",
        "#define SAPI_TABLE_BAKED_H",
        "#define SAPI_BAKED_WORDS %uu" % n,
        "static const unsigned int sapi_table_baked[SAPI_BAKED_WORDS] = {",
    ]
    for i in range(0, n, 8):
        row = "".join("0x%08x," % x for x in w[i:i + 8])
        lines.append("  " + row)
    lines += ["};", "#endif", ""]
    open(out, "w").write("\n".join(lines))
    print("wrote %s: %d words, %d non-zero" % (out, n, nz))


if __name__ == "__main__":
    main()
