#!/usr/bin/env python3
"""gen_pairs.py — emit sapi_pairs.h: the (hash -> slot) pairs init1 (FUN_7e1b1ce0) resolves.

Resolver-replay table fill (../standalone_sapi_test.md RESULT 10): instead of memcpy'ing a captured
partial table (which missed the 58 slots below 0x7e1e2000, e.g. the GNSS URC-attach 0x7e1e1f88), a
standalone replays init1's resolve loop: for each (hash,slot), *slot = resolver(hash). The resolver is
the r0 the loader passes at boot (stashed at 0x7e1e2444). This fills the COMPLETE table.

Parses init1 straight from the vendor image, following the b.n chain across its literal pools. Also emits
the 2 slots init1 does NOT fill but which are non-zero in the runtime capture (filled by other init fns) as
constant supplements, so coverage matches the vendor.

  python3 gen_pairs.py ../fromsrc/app_wstrk.raw ../fromsrc/sapi_table_boot1.bin sapi_pairs.h
"""
import sys, struct

BASE = 0x7E1B0000
INIT1 = 0x7E1B1CE0
TABLE_LO, TABLE_HI = 0x7E1E1E00, 0x7E1E2900
CAP_BASE = 0x7E1E2000
STASH = 0x7E1E2444
DYNAMIC = {0x7E1E2844, 0x7E1E2848, 0x7E1E2850}   # per-boot values, never fill


def main():
    img, cap_path, out = sys.argv[1], sys.argv[2], sys.argv[3]
    raw = open(img, "rb").read()

    def h16(a): return struct.unpack_from("<H", raw, a - BASE)[0]
    def w32(a): return struct.unpack_from("<I", raw, a - BASE)[0]
    def pcrel(a, imm): return ((a + 4) & ~3) + imm

    pairs, seen = [], set()
    addr, last_hash, armed = INIT1, None, False
    for _ in range(40000):
        op = h16(addr)
        if (op & 0xFF00) == 0xBD00:                     # pop {..,pc} -> return
            break
        if (op & 0xF800) == 0x4800:                     # ldr rt,[pc,#imm8*4]
            rt = (op >> 8) & 7
            val = w32(pcrel(addr, (op & 0xFF) * 4))
            if rt == 0:
                last_hash = val
            elif rt == 3:
                nxt = addr + 2
                if h16(nxt) == 0x2100:
                    nxt += 2
                if h16(nxt) == 0x6018 and armed and last_hash is not None:
                    if TABLE_LO <= val <= TABLE_HI and val not in seen and val != STASH:
                        pairs.append((last_hash, val)); seen.add(val)
                    armed = False
            addr += 2; continue
        if op == 0xF8DF:                                # ldr.w rt,[pc,#imm12]
            op2 = h16(addr + 2)
            rt = (op2 >> 12) & 0xF
            val = w32(pcrel(addr, op2 & 0xFFF))
            if rt == 0:
                last_hash = val
            elif rt == 3:
                nxt = addr + 4
                if h16(nxt) == 0x2100:
                    nxt += 2
                if h16(nxt) == 0x6018 and armed and last_hash is not None:
                    if TABLE_LO <= val <= TABLE_HI and val not in seen and val != STASH:
                        pairs.append((last_hash, val)); seen.add(val)
                    armed = False
            addr += 4; continue
        if op == 0x47A0:                                # blx r4 (resolve)
            armed = True; addr += 2; continue
        if (op & 0xF800) == 0xE000:                     # b.n imm11 -> follow
            imm = op & 0x7FF
            if imm & 0x400:
                imm -= 0x800
            addr = addr + 4 + imm * 2; continue
        addr += 2

    # supplements: capture slots non-zero but not init1-filled (and not dynamic / not the stash)
    cap = open(cap_path, "rb").read()
    supp = []
    for i in range(len(cap) // 4):
        a = CAP_BASE + 4 * i
        v = struct.unpack_from("<I", cap, 4 * i)[0]
        if v and a not in seen and a != STASH and a not in DYNAMIC:
            supp.append((a, v))

    lines = [
        "/* sapi_pairs.h — GENERATED by gen_pairs.py from the vendor image. Do not edit. */",
        "/* %d (hash,slot) pairs from init1's resolve loop; %d const supplements (other-init slots). */"
        % (len(pairs), len(supp)),
        "#ifndef SAPI_PAIRS_H",
        "#define SAPI_PAIRS_H",
        "#define SAPI_N_PAIRS %uu" % len(pairs),
        "static const struct { unsigned int hash, slot; } sapi_pairs[SAPI_N_PAIRS] = {",
    ]
    for h, s in pairs:
        lines.append("  {0x%08x,0x%08x}," % (h, s))
    lines += ["};",
              "#define SAPI_N_SUPP %uu" % len(supp),
              "static const struct { unsigned int slot, val; } sapi_supp[SAPI_N_SUPP] = {"]
    for a, v in supp:
        lines.append("  {0x%08x,0x%08x}," % (a, v))
    lines += ["};", "#endif", ""]
    open(out, "w").write("\n".join(lines))
    print("wrote %s: %d pairs, %d supplements; slots 0x%08x..0x%08x, %d below 0x7e1e2000"
          % (out, len(pairs), len(supp), min(s for _, s in pairs), max(s for _, s in pairs),
             sum(1 for _, s in pairs if s < 0x7E1E2000)))


if __name__ == "__main__":
    main()
